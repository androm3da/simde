static int
test_simde_Q_predicate_edges(SIMDE_MUNIT_TEST_ARGS) {
  const uint8_t a[SIMDE_HVX_VECTOR_SIZE] = { 0xff, 0xff, 0, 0, 0xff, 0, 0xff, 0 };
  const uint8_t b[SIMDE_HVX_VECTOR_SIZE] = { 0xff, 0, 0xff, 0, 0, 0xff, 0xff, 0 };
  const uint8_t andn[SIMDE_HVX_VECTOR_SIZE] = { 0, 0xff, 0, 0, 0xff, 0, 0, 0 };
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_and_QQn(simde_test_hvx_vectorpred_load(a), simde_test_hvx_vectorpred_load(b)),
    simde_test_hvx_vectorpred_load(andn));

  const size_t n = (SIMDE_HVX_VECTOR_SIZE / 2) + 1;
  uint8_t setq[SIMDE_HVX_VECTOR_SIZE];
  simde_memset(setq, 0, sizeof(setq));
  simde_memset(setq, 0xff, n);
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq_R(HEDLEY_STATIC_CAST(int32_t, n)), simde_test_hvx_vectorpred_load(setq));
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq2_R(HEDLEY_STATIC_CAST(int32_t, n)), simde_test_hvx_vectorpred_load(setq));

  /* The lane count wraps modulo the vector size. */
  uint8_t setq_wrap[SIMDE_HVX_VECTOR_SIZE];
  simde_memset(setq_wrap, 0, sizeof(setq_wrap));
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq_R(SIMDE_HVX_VECTOR_SIZE), simde_test_hvx_vectorpred_load(setq_wrap));
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq_R(0), simde_test_hvx_vectorpred_load(setq_wrap));

  /* vsetq2 differs from vsetq only when the wrapped count is zero. */
  uint8_t setq2_all[SIMDE_HVX_VECTOR_SIZE];
  simde_memset(setq2_all, 0xff, sizeof(setq2_all));
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq2_R(0), simde_test_hvx_vectorpred_load(setq2_all));
  simde_test_hvx_vectorpred_u8_assert_equal(
    simde_Q6_Q_vsetq2_R(SIMDE_HVX_VECTOR_SIZE), simde_test_hvx_vectorpred_load(setq2_all));

  return 0;
}

