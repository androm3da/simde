static int
test_simde_vfloat_signed_zero(SIMDE_MUNIT_TEST_ARGS) {
  simde_hvx_vector_private a_, b_, r_;

  simde_memset(&a_, 0, sizeof(a_));
  simde_memset(&b_, 0, sizeof(b_));
  a_.u32[1] = UINT32_C(0x80000000);
  b_.u32[0] = UINT32_C(0x80000000);
  r_ = simde_hvx_vector_to_private(simde_Q6_Vsf_vfmax_VsfVsf(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u32(r_.u32[0], UINT32_C(0));
  simde_assert_equal_u32(r_.u32[1], UINT32_C(0));
  r_ = simde_hvx_vector_to_private(simde_Q6_Vsf_vfmin_VsfVsf(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u32(r_.u32[0], UINT32_C(0x80000000));
  simde_assert_equal_u32(r_.u32[1], UINT32_C(0x80000000));

  simde_memset(&a_, 0, sizeof(a_));
  simde_memset(&b_, 0, sizeof(b_));
  a_.u16[1] = UINT16_C(0x8000);
  b_.u16[0] = UINT16_C(0x8000);
  r_ = simde_hvx_vector_to_private(simde_Q6_Vhf_vfmax_VhfVhf(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u16(r_.u16[0], UINT16_C(0));
  simde_assert_equal_u16(r_.u16[1], UINT16_C(0));
  r_ = simde_hvx_vector_to_private(simde_Q6_Vhf_vfmin_VhfVhf(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u16(r_.u16[0], UINT16_C(0x8000));
  simde_assert_equal_u16(r_.u16[1], UINT16_C(0x8000));

  simde_memset(&a_, 0, sizeof(a_));
  simde_memset(&b_, 0, sizeof(b_));
  a_.u8[1] = UINT8_C(0x80);
  b_.u8[0] = UINT8_C(0x80);
  r_ = simde_hvx_vector_to_private(simde_Q6_V_vfmax_VV(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u8(r_.u8[0], UINT8_C(0));
  simde_assert_equal_u8(r_.u8[1], UINT8_C(0));
  r_ = simde_hvx_vector_to_private(simde_Q6_V_vfmin_VV(
    simde_hvx_vector_from_private(a_), simde_hvx_vector_from_private(b_)));
  simde_assert_equal_u8(r_.u8[0], UINT8_C(0x80));
  simde_assert_equal_u8(r_.u8[1], UINT8_C(0x80));

  return 0;
}

